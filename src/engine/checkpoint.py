# ============================================================
# SERIALIZATION
# ============================================================

def to_jsonable(value):

    if isinstance(value, dict):

        return {
            str(key): to_jsonable(item)
            for key, item in value.items()
        }

    if isinstance(value, (list, tuple)):

        return [
            to_jsonable(item)
            for item in value
        ]

    if torch.is_tensor(value):

        if value.numel() == 1:

            return value.detach().cpu().item()

        return value.detach().cpu().tolist()

    if isinstance(value, np.ndarray):

        return value.tolist()

    if isinstance(value, np.generic):

        return value.item()

    if isinstance(value, Path):

        return str(value)

    if isinstance(value, (str, int, float, bool)) or value is None:

        return value

    return str(value)


# ============================================================
# ATOMIC JSON SAVE
# ============================================================

def atomic_write_json(data, filepath):

    filepath = Path(filepath)

    filepath.parent.mkdir(
        parents=True,
        exist_ok=True
    )

    temporary_path = filepath.with_name(
        filepath.name + ".tmp"
    )

    with open(
        temporary_path,
        "w",
        encoding="utf-8"
    ) as file:

        json.dump(

            to_jsonable(data),

            file,

            indent=4,

            ensure_ascii=False,

            allow_nan=False

        )

    os.replace(
        temporary_path,
        filepath
    )


# ============================================================
# MODEL UNWRAPPING
# ============================================================

def unwrap_model(model):

    """
    Handle DataParallel and DistributedDataParallel models.
    """

    if hasattr(model, "module"):

        return model.module

    return model


# ============================================================
# MODEL STATE DICTIONARY
# ============================================================

def get_model_state_dict(model):

    model = unwrap_model(model)

    return {

        key: value.detach().cpu().clone()

        if torch.is_tensor(value)

        else value

        for key, value in model.state_dict().items()

    }


# ============================================================
# RANDOM NUMBER GENERATOR STATE
# ============================================================

def capture_rng_state():

    """
    Capture random states for reproducible resumption.
    """

    state = {

        "python": random.getstate(),

        "numpy": np.random.get_state(),

        "torch_cpu": torch.get_rng_state(),

        "torch_cuda": None,

    }

    if torch.cuda.is_available():

        state["torch_cuda"] = [

            rng_state.cpu()

            for rng_state in torch.cuda.get_rng_state_all()

        ]

    return state


# ============================================================
# RESTORE RANDOM NUMBER GENERATOR STATE
# ============================================================

def restore_rng_state(state):

    if not state:

        warnings.warn(
            "No RNG state found in checkpoint."
        )

        return

    random.setstate(
        state["python"]
    )

    np.random.set_state(
        state["numpy"]
    )

    torch.set_rng_state(
        state["torch_cpu"].cpu()
    )

    cuda_states = state.get(
        "torch_cuda"
    )

    if cuda_states is not None:

        if torch.cuda.is_available():

            if len(cuda_states) == torch.cuda.device_count():

                torch.cuda.set_rng_state_all(
                    cuda_states
                )

            else:

                warnings.warn(

                    "Saved CUDA device count differs from "
                    "the current environment. CUDA RNG "
                    "states were not restored."

                )

        else:

            warnings.warn(

                "Checkpoint contains CUDA RNG states, "
                "but CUDA is unavailable."

            )


# ============================================================
# CHECKPOINT MANAGER
# ============================================================

class CheckpointManager:

    def __init__(
        self,
        output_dir,
        save_last=True
    ):

        self.output_dir = Path(output_dir)

        self.checkpoint_dir = (
            self.output_dir / "checkpoints"
        )

        self.checkpoint_dir.mkdir(

            parents=True,

            exist_ok=True

        )

        # ----------------------------------------------------
        # Checkpoint paths
        # ----------------------------------------------------

        self.best_checkpoint_path = (

            self.checkpoint_dir / "best_model.pth"

        )

        self.last_checkpoint_path = (

            self.checkpoint_dir / "last_checkpoint.pth"

        )

        self.best_info_path = (

            self.checkpoint_dir / "best_model_info.json"

        )

        self.save_last = bool(save_last)

        # ----------------------------------------------------
        # Best model tracking
        # ----------------------------------------------------

        self.best_metric = None

        self.best_epoch = None

        self.best_metric_name = None

    # ========================================================
    # ATOMIC TORCH SAVE
    # ========================================================

    @staticmethod
    def _atomic_torch_save(
        checkpoint,
        filepath
    ):

        filepath = Path(filepath)

        filepath.parent.mkdir(
            parents=True,
            exist_ok=True
        )

        temporary_path = filepath.with_name(
            filepath.name + ".tmp"
        )

        try:

            torch.save(
                checkpoint,
                temporary_path
            )

            os.replace(
                temporary_path,
                filepath
            )

        except Exception:

            if temporary_path.exists():

                temporary_path.unlink()

            raise

    # ========================================================
    # BUILD CHECKPOINT
    # ========================================================

    def _build_checkpoint(

        self,

        model,

        optimizer,

        scheduler,

        scaler,

        early_stopping,

        epoch,

        global_step,

        model_name,

        metric_name,

        metric_value,

        config,

        compatibility,

        dataset_metadata,

        environment_metadata,

        extra

    ):

        early_stopping_state = (

            early_stopping.state_dict()

            if early_stopping is not None

            else None

        )

        checkpoint = {

            "checkpoint_version": CHECKPOINT_VERSION,

            "created_at": datetime.now(
                timezone.utc
            ).isoformat(),

            "model_name": model_name,

            "epoch": int(epoch),

            "completed_epoch": int(epoch),

            "next_epoch": int(epoch + 1),

            "global_step": int(global_step),

            # Model

            "model_state_dict": get_model_state_dict(
                model
            ),

            # Optimizer

            "optimizer_state_dict": (

                optimizer.state_dict()

                if optimizer is not None

                else None

            ),

            # Scheduler

            "scheduler_state_dict": (

                scheduler.state_dict()

                if scheduler is not None

                else None

            ),

            # AMP

            "scaler_state_dict": (

                scaler.state_dict()

                if scaler is not None

                else None

            ),

            # Early stopping

            "early_stopping_state_dict": (
                early_stopping_state
            ),

            # Best model

            "best_metric": self.best_metric,

            "best_epoch": self.best_epoch,

            "best_metric_name": self.best_metric_name,

            "current_metric_name": metric_name,

            "current_metric_value": (

                float(metric_value)

                if metric_value is not None

                else None

            ),

            # Reproducibility

            "rng_state": capture_rng_state(),

            # Experiment information

            "config": config or {},

            "compatibility": compatibility or {},

            "dataset_metadata": dataset_metadata or {},

            "environment_metadata": environment_metadata or {},

            "extra": extra or {},

        }

        return checkpoint

    # ========================================================
    # SAVE CHECKPOINT
    # ========================================================

    def save(

        self,

        model,

        epoch,

        global_step,

        optimizer=None,

        scheduler=None,

        scaler=None,

        early_stopping=None,

        model_name=None,

        metric_name=None,

        metric_value=None,

        is_best=False,

        config=None,

        compatibility=None,

        dataset_metadata=None,

        environment_metadata=None,

        extra=None

    ):

        """
        Save complete training state.

        is_best:
            True when the monitored validation metric improves.

        The latest checkpoint is saved independently of
        whether the current epoch is the best epoch.
        """

        if epoch < 1:

            raise ValueError(
                "Epoch must be at least 1."
            )

        if global_step < 0:

            raise ValueError(
                "Global step cannot be negative."
            )

        if is_best:

            if metric_name is None or metric_value is None:

                raise ValueError(

                    "Best checkpoint requires metric_name "
                    "and metric_value."

                )

            metric_value = float(metric_value)

            if not np.isfinite(metric_value):

                raise ValueError(
                    "Best metric must be finite."
                )

            self.best_metric = metric_value

            self.best_epoch = int(epoch)

            self.best_metric_name = str(metric_name)

        # ----------------------------------------------------
        # Build full checkpoint
        # ----------------------------------------------------

        checkpoint = self._build_checkpoint(

            model=model,

            optimizer=optimizer,

            scheduler=scheduler,

            scaler=scaler,

            early_stopping=early_stopping,

            epoch=epoch,

            global_step=global_step,

            model_name=model_name,

            metric_name=metric_name,

            metric_value=metric_value,

            config=config,

            compatibility=compatibility,

            dataset_metadata=dataset_metadata,

            environment_metadata=environment_metadata,

            extra=extra

        )

        saved_paths = {}

        # ----------------------------------------------------
        # Save latest checkpoint
        # ----------------------------------------------------

        if self.save_last:

            self._atomic_torch_save(

                checkpoint,

                self.last_checkpoint_path

            )

            saved_paths["last_checkpoint"] = str(
                self.last_checkpoint_path
            )

        # ----------------------------------------------------
        # Save best checkpoint
        # ----------------------------------------------------

        if is_best:

            self._atomic_torch_save(

                checkpoint,

                self.best_checkpoint_path

            )

            best_info = {

                "model_name": model_name,

                "best_epoch": self.best_epoch,

                "best_metric_name": self.best_metric_name,

                "best_metric_value": self.best_metric,

                "checkpoint": str(
                    self.best_checkpoint_path
                ),

                "created_at": checkpoint["created_at"],

                "completed_epoch": int(epoch),

                "global_step": int(global_step),

            }

            atomic_write_json(

                best_info,

                self.best_info_path

            )

            saved_paths["best_checkpoint"] = str(
                self.best_checkpoint_path
            )

        return saved_paths

    # ========================================================
    # LOAD CHECKPOINT
    # ========================================================

    def load(

        self,

        model,

        checkpoint_path=None,

        optimizer=None,

        scheduler=None,

        scaler=None,

        early_stopping=None,

        restore_rng=True,

        strict_model=True,

        expected_compatibility=None,

        strict_compatibility=True,

        strict_early_stopping=True

    ):

        """
        Restore complete training state.

        Checkpoint tensors are initially loaded onto CPU.
        Model and optimizer restoration then use their
        appropriate device placement.

        Only load trusted project checkpoints.
        """

        if checkpoint_path is None:

            checkpoint_path = self.last_checkpoint_path

        checkpoint_path = Path(
            checkpoint_path
        )

        if not checkpoint_path.is_file():

            raise FileNotFoundError(

                f"Checkpoint not found: {checkpoint_path}"

            )

        # ----------------------------------------------------
        # Load checkpoint
        # ----------------------------------------------------

        try:

            checkpoint = torch.load(

                checkpoint_path,

                map_location="cpu",

                weights_only=False

            )

        except TypeError:

            # Compatibility with older PyTorch versions.

            checkpoint = torch.load(

                checkpoint_path,

                map_location="cpu"

            )

        if not isinstance(checkpoint, dict):

            raise ValueError(
                "Invalid checkpoint format."
            )

        version = checkpoint.get(
            "checkpoint_version"
        )

        if version != CHECKPOINT_VERSION:

            raise ValueError(

                f"Unsupported checkpoint version: {version}"

            )

        # ----------------------------------------------------
        # Compatibility verification
        # ----------------------------------------------------

        saved_compatibility = checkpoint.get(
            "compatibility",
            {}
        )

        if expected_compatibility is not None:

            for key, expected_value in (
                expected_compatibility.items()
            ):

                saved_value = saved_compatibility.get(
                    key
                )

                if saved_value != expected_value:

                    message = (

                        f"Checkpoint compatibility mismatch: "

                        f"{key}. "

                        f"Saved={saved_value!r}, "

                        f"Current={expected_value!r}"

                    )

                    if strict_compatibility:

                        raise ValueError(message)

                    warnings.warn(message)

        # ----------------------------------------------------
        # Model restoration
        # ----------------------------------------------------

        if "model_state_dict" not in checkpoint:

            raise ValueError(
                "Checkpoint does not contain model weights."
            )

        model = unwrap_model(model)

        model.load_state_dict(

            checkpoint["model_state_dict"],

            strict=strict_model

        )

        # ----------------------------------------------------
        # Optimizer restoration
        # ----------------------------------------------------

        optimizer_state = checkpoint.get(
            "optimizer_state_dict"
        )

        if optimizer is not None:

            if optimizer_state is None:

                warnings.warn(
                    "Optimizer state missing from checkpoint."
                )

            else:

                optimizer.load_state_dict(
                    optimizer_state
                )

        # ----------------------------------------------------
        # Scheduler restoration
        # ----------------------------------------------------

        scheduler_state = checkpoint.get(
            "scheduler_state_dict"
        )

        if scheduler is not None:

            if scheduler_state is None:

                warnings.warn(
                    "Scheduler state missing from checkpoint."
                )

            else:

                scheduler.load_state_dict(
                    scheduler_state
                )

        # ----------------------------------------------------
        # AMP scaler restoration
        # ----------------------------------------------------

        scaler_state = checkpoint.get(
            "scaler_state_dict"
        )

        if scaler is not None:

            if scaler_state is None:

                warnings.warn(
                    "AMP GradScaler state missing from checkpoint."
                )

            else:

                scaler.load_state_dict(
                    scaler_state
                )

        # ----------------------------------------------------
        # Early stopping restoration
        # ----------------------------------------------------

        early_state = checkpoint.get(
            "early_stopping_state_dict"
        )

        if early_stopping is not None:

            if early_state is None:

                warnings.warn(
                    "Early stopping state missing from checkpoint."
                )

            else:

                early_stopping.load_state_dict(

                    early_state,

                    strict_config=strict_early_stopping

                )

        # ----------------------------------------------------
        # Restore best metric information
        # ----------------------------------------------------

        self.best_metric = checkpoint.get(
            "best_metric"
        )

        self.best_epoch = checkpoint.get(
            "best_epoch"
        )

        self.best_metric_name = checkpoint.get(
            "best_metric_name"
        )

        # ----------------------------------------------------
        # Restore RNG LAST
        # ----------------------------------------------------

        if restore_rng:

            restore_rng_state(
                checkpoint.get("rng_state")
            )

        # ----------------------------------------------------
        # Return resume information
        # ----------------------------------------------------

        return {

            "checkpoint_path": str(
                checkpoint_path
            ),

            "model_name": checkpoint.get(
                "model_name"
            ),

            "completed_epoch": int(
                checkpoint["completed_epoch"]
            ),

            "next_epoch": int(
                checkpoint["next_epoch"]
            ),

            "global_step": int(
                checkpoint["global_step"]
            ),

            "best_metric": self.best_metric,

            "best_epoch": self.best_epoch,

            "best_metric_name": self.best_metric_name,

            "compatibility": saved_compatibility,

            "config": checkpoint.get(
                "config",
                {}
            ),

            "dataset_metadata": checkpoint.get(
                "dataset_metadata",
                {}
            ),

            "environment_metadata": checkpoint.get(
                "environment_metadata",
                {}
            ),

            "extra": checkpoint.get(
                "extra",
                {}
            ),

        }

    # ========================================================
    # LOAD MODEL WEIGHTS ONLY
    # ========================================================

    def load_model_weights(

        self,

        model,

        checkpoint_path=None,

        strict=True

    ):

        """
        Load model weights for inference or evaluation.

        Does not restore optimizer, scheduler or RNG.
        """

        if checkpoint_path is None:

            checkpoint_path = self.best_checkpoint_path

        checkpoint_path = Path(
            checkpoint_path
        )

        if not checkpoint_path.is_file():

            raise FileNotFoundError(
                f"Checkpoint not found: {checkpoint_path}"
            )

        try:

            checkpoint = torch.load(

                checkpoint_path,

                map_location="cpu",

                weights_only=False

            )

        except TypeError:

            checkpoint = torch.load(

                checkpoint_path,

                map_location="cpu"

            )

        unwrap_model(model).load_state_dict(

            checkpoint["model_state_dict"],

            strict=strict

        )

        return {

            "model_name": checkpoint.get("model_name"),

            "epoch": checkpoint.get("completed_epoch"),

            "best_metric": checkpoint.get("best_metric"),

            "best_epoch": checkpoint.get("best_epoch"),

        }

    # ========================================================
    # INSPECT CHECKPOINT
    # ========================================================

